from Bio import SeqIO

genes = {}

for record in SeqIO.parse("rcsb_pdb_1L2Y.fasta", "fasta"):
    genes[record.id] = str(record.seq).upper()

limit = 80
duplicates = 0
total = 0

print("GENE DUPLICATION DETECTOR")

gene_names = list(genes.keys())

for i in range(len(gene_names)):
    for j in range(i + 1, len(gene_names)):

        name1 = gene_names[i]
        name2 = gene_names[j]
        seq1 = genes[name1]
        seq2 = genes[name2]

        total = total + 1

        print("\nComparing", name1, "and", name2)

        if len(seq1) != len(seq2):
            print("Sequences have different lengths.")
            print("Alignment is needed to compare them.")

        elif len(seq1) == 0:
            print("Cannot compare empty sequences.")

        else:
            matches = 0
            for k in range(len(seq1)):
                if seq1[k] == seq2[k]:
                    matches = matches + 1

            identity = (matches / len(seq1)) * 100
            print("Percentage identity:", round(identity, 2), "%")

            if identity >= limit:
                print("Possible gene duplication detected!")
                duplicates = duplicates + 1
            else:
                print("No potential duplication detected.")

print("\nFINAL RESULTS")
print("Total comparisons:", total)
print("Potential duplicate pairs:", duplicates)